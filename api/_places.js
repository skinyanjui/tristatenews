const STATE_ABBR = { kentucky: 'ky', indiana: 'ind', illinois: 'ill', 'ky.': 'ky', 'ind.': 'ind', 'ill.': 'ill', ky: 'ky', ind: 'ind', ill: 'ill', in: 'ind', il: 'ill' };
const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); // for a RegExp source, not HTML
const words = list => new RegExp('(?:^|[^a-z])(?:' + list.map(escRe).join('|') + ')(?![a-z])');
const ANY = words([].concat(PLACES.ind.anywhere, PLACES.ky.anywhere, PLACES.ill.anywhere));
const LOCAL = { ind: words(PLACES.ind.local), ky: words(PLACES.ky.local), ill: words(PLACES.ill.local) };

// "Henderson, Kentucky" / "Henderson, Ky." / "Carmi, IL" -> "henderson, ky" / "carmi, ill"
function fold(text) {
  return String(text || '').toLowerCase().replace(/\u2019/g, "'")
    .replace(/,\s*(kentucky|indiana|illinois|ky\.?|ind\.?|ill\.?|in|il)(?![a-z])/g, (m, st) => ', ' + STATE_ABBR[st]);
}
// state: the feed's own state ('ind', 'ky' or 'ill'), or null for a feed that is not tied to one state.
function inTriState(item, state) {
  const hay = fold((item.title || '') + ' ' + (item.summary || ''));
  if (ANY.test(hay)) return true;
  return !!(state && LOCAL[state] && LOCAL[state].test(hay));
}

// ---- Locality lookups over the 68-county tables (api/_geo.js, generated by scripts/build-geo.js) ----
// Not used by any route yet: inTriState above still drives the FBI/U.S. Attorney filter, unchanged.
// locate(text, { feedState }) finds every place or county alias in the text and says how each was resolved:
//   with_state           "Marion, Ill." / "Perry County, Indiana": the alias has exactly one candidate in that state
//   unique_locality      a name with no namesake in the area or elsewhere ("Owensboro", "Vanderburgh")
//   feed_state           a name with namesakes elsewhere but one local candidate, bare in a feed from that state
//   co_occurring_county  an ambiguous name whose candidates are narrowed to one by a county named in the same text
// Ambiguous names (Marion, Mount Vernon, Washington, Princeton, Perry County ...) never resolve from the feed's state.
// What cannot be resolved is returned in `unresolved` for review; a name qualified with another state
// ("Henderson, Nevada", "Marion, Ind.") is returned in `rejected`.
let GEO = null;
const AP_STATES = { 'ala.': 'AL', 'ariz.': 'AZ', 'ark.': 'AR', 'calif.': 'CA', 'colo.': 'CO', 'conn.': 'CT', 'del.': 'DE', 'fla.': 'FL', 'ga.': 'GA',
  'ill.': 'IL', 'ind.': 'IN', 'kan.': 'KS', 'ky.': 'KY', 'la.': 'LA', 'md.': 'MD', 'mass.': 'MA', 'mich.': 'MI', 'minn.': 'MN', 'miss.': 'MS', 'mo.': 'MO',
  'mont.': 'MT', 'neb.': 'NE', 'nev.': 'NV', 'n.h.': 'NH', 'n.j.': 'NJ', 'n.m.': 'NM', 'n.y.': 'NY', 'n.c.': 'NC', 'n.d.': 'ND', 'okla.': 'OK', 'ore.': 'OR',
  'pa.': 'PA', 'r.i.': 'RI', 's.c.': 'SC', 's.d.': 'SD', 'tenn.': 'TN', 'vt.': 'VT', 'va.': 'VA', 'wash.': 'WA', 'w.va.': 'WV', 'wis.': 'WI', 'wyo.': 'WY',
  'd.c.': 'DC' };
const FEED_STATE = { ind: 'IN', ky: 'KY', ill: 'IL', mo: 'MO', IN: 'IN', KY: 'KY', IL: 'IL', MO: 'MO' };
function geo() {
  if (GEO) return GEO;
  const data = require('./_geo.js');
  const byForm = new Map();
  for (const a of data.aliases) for (const f of a.forms) byForm.set(f, a);
  const formRe = new RegExp('(?<![a-z0-9])(' + [...byForm.keys()].sort((x, y) => y.length - x.length || (x < y ? -1 : 1)).map(escRe).join('|') + ')(?![a-z0-9])', 'g');
  const names = Object.entries(data.states).map(([p, n]) => [n.toLowerCase(), p]);
  const nameRe = new RegExp(',\\s*(' + names.map(([n]) => escRe(n)).sort((x, y) => y.length - x.length).join('|') + ')(?![a-z])', 'gi');
  const apRe = new RegExp(',\\s*(' + Object.keys(AP_STATES).sort((x, y) => y.length - x.length).map(escRe).join('|') + ')', 'gi');
  const postalRe = new RegExp(',\\s*(' + Object.keys(data.states).join('|') + ')(?![A-Za-z])', 'g'); // capitals only: ", IN" not ", in a"
  const core = new Set(data.counties.filter(c => c.groups.includes('tri_state_core')).map(c => c.id));
  GEO = { data, byForm, formRe, nameRe, apRe, postalRe, stateOf: new Map(names), core };
  return GEO;
}
// State qualifiers become ", @xx" (postal code, lower case) so they survive lower-casing and cannot match an alias.
function foldGeo(text) {
  const g = geo();
  return String(text || '').replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, ' ')
    .replace(g.nameRe, (m, n) => ', @' + g.stateOf.get(n.toLowerCase()).toLowerCase())
    .replace(g.apRe, (m, a) => ', @' + AP_STATES[a.toLowerCase()].toLowerCase())
    .replace(g.postalRe, (m, p) => ', @' + p.toLowerCase())
    .toLowerCase();
}
function locate(text, opts) {
  const g = geo();
  const feed = FEED_STATE[(opts && opts.feedState) || ''] || null;
  const hay = foldGeo(text);
  const found = [];
  g.formRe.lastIndex = 0;
  for (let m; (m = g.formRe.exec(hay));) {
    const a = g.byForm.get(m[1]);
    const q = /^,\s*@([a-z]{2})/.exec(hay.slice(m.index + m[1].length));
    found.push({ a, text: m[1], qualifier: q ? q[1].toUpperCase() : null });
  }
  const out = { matches: [], unresolved: [], rejected: [] };
  const hit = (f, ref, method) => ({ alias: f.a.alias, text: f.text, type: ref.type, id: ref.id, state: ref.state, countyIds: ref.countyIds, method, ambiguous: f.a.ambiguous });
  const pending = [];
  for (const f of found) {
    const refs = f.a.refs;
    if (f.qualifier) {
      const inState = refs.filter(r => r.state === f.qualifier);
      if (inState.length === 1) out.matches.push(hit(f, inState[0], 'with_state'));
      else if (inState.length) pending.push({ f, cands: inState });
      else out.rejected.push({ alias: f.a.alias, text: f.text, qualifier: f.qualifier });
    } else if (!f.a.requiresState && refs.length === 1) out.matches.push(hit(f, refs[0], 'unique_locality'));
    else if (!f.a.ambiguous && feed && refs.length === 1 && refs[0].state === feed) out.matches.push(hit(f, refs[0], 'feed_state'));
    else pending.push({ f, cands: refs });
  }
  const named = new Set(out.matches.filter(m => m.type === 'county').map(m => m.id));
  for (const { f, cands } of pending) {
    const pick = cands.filter(r => r.countyIds.some(c => named.has(c)));
    if (pick.length === 1) out.matches.push(hit(f, pick[0], 'co_occurring_county'));
    else out.unresolved.push({ alias: f.a.alias, text: f.text, reasons: f.a.reasons, candidates: cands.map(r => ({ id: r.id, state: r.state, countyIds: r.countyIds })) });
  }
  return out;
}
// True when an item names a place or county in the 30-county Tri-State core. The planned successor to inTriState
// for the strict filter; not wired in (reader-facing changes ship behind a flag, plan D1).
function inCore30(item, state) {
  const g = geo();
  return locate((item.title || '') + ' ' + (item.summary || ''), { feedState: state }).matches.some(m => m.countyIds.some(c => g.core.has(c)));
}
